#!/usr/bin/env node

/**
 * GitHub Actions Debug Report PR Commenter
 *
 * Automatically posts CI debug reports as PR comments when workflows fail.
 * Research basis: GitHub API for issue/PR comments.
 *
 * Usage:
 *   node scripts/pr-debug-comment.mjs --run-id <id> --repo <owner/repo> --report <path>
 *
 * Environment:
 *   GITHUB_TOKEN - PAT with repo scope (or GITHUB_TOKEN in workflow)
 */

import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const API_BASE = 'https://api.github.com';
const API_TIMEOUT_MS = 30_000;
const MAX_INLINE_CODE = 120;
const COMMENT_MARKER = 'CI Failure Debug Report';

/**
 * Collapse untrusted text into a value that is safe inside a Markdown code span.
 *
 * `run.head_branch` names the pull request's head branch, which for a fork is
 * fully attacker-controlled. Interpolating it raw let a branch name close the
 * surrounding backtick span and inject Markdown into a comment posted by the
 * trusted default-branch workflow. Strip control characters, newlines and
 * backticks, collapse whitespace, and bound the length.
 *
 * @param {unknown} value
 * @param {string} [fallback]
 * @returns {string}
 */
export function sanitizeInlineCode(value, fallback = 'unknown') {
  if (typeof value !== 'string') return fallback;
  const cleaned = value
    // Turn line breaks into spaces first so words do not run together, then
    // drop any remaining control characters.
    .replace(/[\r\n\t]+/g, ' ')
    .replace(/\p{Cc}/gu, '')
    .replace(/`/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  return cleaned.length > 0 ? cleaned.slice(0, MAX_INLINE_CODE) : fallback;
}

/**
 * Decide whether an existing issue comment may be adopted (updated in place).
 *
 * Only the authenticated commenter's own comment may be rewritten. Any
 * contributor can type the report marker into a comment; without this fence a
 * fork PR author could get the bot to overwrite their comment with trusted
 * content. A missing identity means "never adopt", not "adopt anything".
 *
 * @param {{user?: {login?: string}, body?: string}} comment
 * @param {string | null} actorLogin
 * @returns {boolean}
 */
export function isUpdateableComment(comment, actorLogin) {
  if (!actorLogin) return false;
  if (!comment?.body?.includes(COMMENT_MARKER)) return false;
  return comment.user?.login === actorLogin;
}

/**
 * Build the PR comment body from trusted metadata plus the generated report.
 *
 * @param {{
 *   repo: string,
 *   runId: string | number,
 *   runName?: string,
 *   runBranch?: string,
 *   runSha?: string,
 *   reportContent: string,
 * }} input
 * @returns {string}
 */
export function buildCommentBody(input) {
  const { repo, runId, runName, runBranch, runSha, reportContent } = input;
  const shortSha =
    typeof runSha === 'string' && runSha.length >= 7
      ? runSha.slice(0, 7)
      : sanitizeInlineCode(runSha);
  return `## ${COMMENT_MARKER}

**Workflow:** ${sanitizeInlineCode(runName, 'Unknown')}
**Run:** [${runId}](https://github.com/${repo}/actions/runs/${runId})
**Branch:** \`${sanitizeInlineCode(runBranch)}\`
**Commit:** \`${shortSha}\`

---

${reportContent}

---

<details>
<summary>Posted by the automated CI debug system</summary>

This comment was automatically generated by the Varve CI/CD pipeline.
To disable these comments, remove the PR debug step from the workflow.
</details>
`;
}

function parseArgs() {
  const args = process.argv.slice(2);
  const flags = {
    runId: process.env.GITHUB_RUN_ID,
    repo: process.env.GITHUB_REPOSITORY,
    report: 'ci-debug-report.md',
    dryRun: false,
  };

  for (let i = 0; i < args.length; i += 1) {
    const arg = args[i];
    if (arg === '--run-id' || arg === '-r') {
      flags.runId = args[i + 1];
      i += 1;
    } else if (arg === '--repo') {
      flags.repo = args[i + 1];
      i += 1;
    } else if (arg === '--report' || arg === '-f') {
      flags.report = args[i + 1];
      i += 1;
    } else if (arg === '--dry-run') {
      flags.dryRun = true;
    }
  }

  return flags;
}

function getAuthToken() {
  if (process.env.GITHUB_TOKEN) return process.env.GITHUB_TOKEN;
  return null;
}

async function githubFetch(path, token, { method = 'GET', body } = {}) {
  const url = path.startsWith('http') ? path : `${API_BASE}${path}`;
  const headers = {
    Accept: 'application/vnd.github+json',
    'X-GitHub-Api-Version': '2022-11-28',
    Authorization: token ? `Bearer ${token}` : undefined,
  };
  if (body !== undefined) headers['Content-Type'] = 'application/json';

  // Bound every request. A hung socket otherwise burns the job's entire
  // timeout and produces no comment and no diagnosis.
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), API_TIMEOUT_MS);
  let res;
  try {
    res = await fetch(url, {
      method,
      headers,
      body: body === undefined ? undefined : JSON.stringify(body),
      signal: controller.signal,
    });
  } catch (error) {
    if (error?.name === 'AbortError') {
      throw new Error(`GitHub API request timed out after ${API_TIMEOUT_MS / 1000}s: ${url}`);
    }
    throw error;
  } finally {
    clearTimeout(timeout);
  }

  if (!res.ok) {
    const errorBody = await res.text();
    throw new Error(
      `GitHub API ${url} failed: ${res.status} ${res.statusText}\n${errorBody.slice(0, 500)}`,
    );
  }

  return res;
}

async function githubJson(path, token) {
  const res = await githubFetch(path, token);
  return res.json();
}

async function getAuthenticatedLogin(token) {
  const data = await githubJson('/user', token);
  return typeof data?.login === 'string' && data.login.length > 0 ? data.login : null;
}

async function getRunMeta(repo, runId, token) {
  const [owner, name] = repo.split('/');
  return githubJson(`/repos/${owner}/${name}/actions/runs/${runId}`, token);
}

async function findPullRequest(repo, runSha, token) {
  const [owner, name] = repo.split('/');
  const data = await githubJson(
    `/repos/${owner}/${name}/pulls?state=open&sort=updated&per_page=10`,
    token,
  );

  // Find PR that contains the commit SHA
  for (const pr of data) {
    const prData = await githubJson(pr.url, token);
    if (prData.head.sha === runSha) {
      return prData;
    }
  }

  return null;
}

async function findExistingComment(repo, prNumber, token, actorLogin) {
  const [owner, name] = repo.split('/');
  const data = await githubJson(
    `/repos/${owner}/${name}/issues/${prNumber}/comments?per_page=100`,
    token,
  );

  // Adopt only the bot's own comment (see isUpdateableComment). A contributor
  // can type the marker string; the author fence keeps the bot from rewriting
  // someone else's comment with trusted content.
  for (const comment of data) {
    if (isUpdateableComment(comment, actorLogin)) return comment;
  }

  return null;
}

async function createComment(repo, prNumber, body, token) {
  const [owner, name] = repo.split('/');
  return (
    await githubFetch(`/repos/${owner}/${name}/issues/${prNumber}/comments`, token, {
      method: 'POST',
      body: { body },
    })
  ).json();
}

async function updateComment(repo, commentId, body, token) {
  const [owner, name] = repo.split('/');
  return (
    await githubFetch(`/repos/${owner}/${name}/issues/comments/${commentId}`, token, {
      method: 'PATCH',
      body: { body },
    })
  ).json();
}

async function main() {
  const args = parseArgs();

  if (!args.repo) {
    throw new Error('Repository required. Use --repo or set GITHUB_REPOSITORY.');
  }

  if (!args.runId) {
    throw new Error('Run ID required. Use --run-id or set GITHUB_RUN_ID.');
  }

  const token = getAuthToken();
  if (!token) {
    throw new Error('GitHub token required. Set GITHUB_TOKEN.');
  }

  // Read debug report
  let reportContent;
  try {
    reportContent = readFileSync(args.report, 'utf8');
  } catch {
    throw new Error(`Could not read report file: ${args.report}`);
  }

  // Get run metadata
  console.log(`Fetching run ${args.runId}...`);
  const run = await getRunMeta(args.repo, args.runId, token);

  // Find associated PR
  console.log(`Looking for PR with commit ${run.head_sha}...`);
  const pr = await findPullRequest(args.repo, run.head_sha, token);

  if (!pr) {
    console.log('No open PR found for this run. Skipping comment.');
    return;
  }

  console.log(`Found PR #${pr.number}: ${sanitizeInlineCode(pr.title, 'untitled')}`);

  const commentBody = buildCommentBody({
    repo: args.repo,
    runId: args.runId,
    runName: run.name,
    runBranch: run.head_branch,
    runSha: run.head_sha,
    reportContent,
  });

  if (args.dryRun) {
    console.log('\n=== Dry Run: Comment that would be posted ===');
    console.log(commentBody);
    console.log('\n=== End Dry Run ===');
    return;
  }

  // Identify the authenticated commenter so only its own previous comment is
  // ever adopted (see isUpdateableComment).
  const actorLogin = await getAuthenticatedLogin(token);
  if (!actorLogin) {
    console.warn('Could not resolve the authenticated login; posting a new comment.');
  }

  // Check for existing comment
  console.log('Checking for existing debug comment...');
  const existingComment = await findExistingComment(args.repo, pr.number, token, actorLogin);

  if (existingComment) {
    console.log(`Updating existing comment #${existingComment.id}...`);
    await updateComment(args.repo, existingComment.id, commentBody, token);
    console.log('Comment updated');
  } else {
    console.log(`Creating new comment on PR #${pr.number}...`);
    await createComment(args.repo, pr.number, commentBody, token);
    console.log('Comment created');
  }
}

// Entry guard: compare canonical file URLs, not a hand-built `file://` string.
// The naive `file://${process.argv[1]}` never matches on Windows and silently
// skips main() for any checkout path containing spaces or non-ASCII characters.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((err) => {
    console.error(`Error: ${err.message}`);
    process.exit(1);
  });
}
