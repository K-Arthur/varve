  minus: '\u2212',
  plusmn: '\u00B1',
  ne: '\u2260',
  le: '\u2264',
  ge: '\u2265',
  asymp: '\u2248',
  infin: '\u221E',
  deg: '\u00B0',
  eacute: '\u00E9',
