/**
 * Build-time HTML extraction for the website search index.
 *
 * The website is 100+ hand-authored Astro pages, so there is no Markdown
 * pipeline to hook into. This module reads the *built* HTML instead — the
 * real output users receive — and does two jobs in one pass over `<main>`:
 *
 *  1. injects stable `id`s on `h2`/`h3` headings so sections are linkable
 *     (the source pages mostly have none), and
 *  2. returns heading-delimited sections (heading + plain text) for the index.
 *
 * It is deliberately a small string processor rather than an HTML parser:
 * the corpus is generated by Astro with predictable structure, there is no
 * new dependency, and every rule here is covered by unit tests and by E2E
 * queries against the real built site.
 */

import type { SearchPage, SearchSection } from './types';

const MAIN_RE = /<main\b([^>]*)>([\s\S]*?)<\/main>/i;

interface HeadingRecord {
  level: number;
  id: string;
  text: string;
  /** Index of the opening `<hN` in the source main HTML. */
  start: number;
  /** Index just past the closing `</hN>` in the source main HTML. */
  end: number;
}

export interface ExtractedPage {
  page: SearchPage;
  /** Full document HTML with heading anchors injected. */
  html: string;
}

