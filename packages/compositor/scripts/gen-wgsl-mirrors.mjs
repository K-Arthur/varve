#!/usr/bin/env node
/**
 * Generates the naga-validation mirrors for the live-effects WGSL kernels.
 *
 * The WGSL lives in TypeScript (packages/compositor/src/webgpu/effects/
 * kernels/*.ts, built as `WGSL_HELPERS + template`). This script extracts
 * the concatenated strings and regenerates the Rust consts in
 * crates/varve-bridge/tests/wgsl_validation.rs, which naga compiles in Rust
 * CI — the cross-platform compile gate for the GPU shaders.
 *
 * Run after changing any effect kernel WGSL:
 *   node packages/compositor/scripts/gen-wgsl-mirrors.mjs
 *   cargo test -p varve-bridge wgsl_validation
 *
 * The compositor's wgsl-drift test keeps the TS and Rust copies in sync.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const kernelsDir = join(root, 'packages', 'compositor', 'src', 'webgpu', 'effects', 'kernels');
const mirrorPath = join(root, 'crates', 'varve-bridge', 'tests', 'wgsl_validation.rs');

const KERNEL_IDS = [
  'rgbSplit',
  'crt',
  'lightLeak',
  'paletteSnap',
  'vhs',
  'lightShafts',
  'caustics',
  'lensFlare',
  'bloom',
];

function constNameFor(id) {
  return id.toUpperCase().replace(/[^A-Z0-9]/g, '_');
}

function extractHelpers() {
  const src = readFileSync(join(kernelsDir, 'shared.ts'), 'utf8');
  const m = src.match(/export const WGSL_HELPERS = \/\* wgsl \*\/ `([\s\S]*?)`;/);
  if (!m) throw new Error('WGSL_HELPERS not found in shared.ts');
  return m[1];
}

function extractKernelWgsl(kernelId) {
  const src = readFileSync(join(kernelsDir, `${kernelId}.ts`), 'utf8');
  // kernels use `WGSL_HELPERS + /* wgsl */ `...`` or a plain template;
  // rgbSplit concatenates two templates. Greedy capture to the FINAL
  // closing, then drop the ` + ` separators between the fragments.
  const pattern =
    /wgsl:\s*\n\s*(?:WGSL_HELPERS\s*\+\s*)?(?:\/\* wgsl \*\/ )?`\n([\s\S]*)\n`,\n {2}buildPasses/;
  const m = src.match(pattern);
  if (!m) throw new Error(`wgsl template not found for ${kernelId}`);
  return m[1].replace(/`\s*\+\s*\n\s*`/g, '');
}

const helpers = extractHelpers();
const sections = [];
for (const id of KERNEL_IDS) {
  const body = extractKernelWgsl(id);
  const full = `${helpers}\n${body}`;
  const constName = `${constNameFor(id)}_WGSL`;
  sections.push(`const ${constName}: &str = r#"${full}"#;`);
}

const validation = KERNEL_IDS.map(
  (id) => `    validate(${constNameFor(id)}_WGSL, "${constNameFor(id)}_WGSL", true);`,
).join('\n');

const header = readFileSync(mirrorPath, 'utf8').split('// ---- effect kernels (generated) ----')[0];
const footer = `
// ---- effect kernels (generated) ----
// Generated by packages/compositor/scripts/gen-wgsl-mirrors.mjs — do not edit.

${sections.join('\n\n')}

#[test]
fn effect_kernel_wgsl_compiles() {
${validation}
}
`;

writeFileSync(mirrorPath, `${header.trimEnd()}\n${footer}`);
console.log(`wgsl mirrors written to ${mirrorPath}`);
