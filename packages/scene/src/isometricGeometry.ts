/**
 * Canonical isometric / axonometric construction geometry.
 *
 * One mathematical definition consumed by the overlay renderer, the snapping
 * solver, plane-aware tools, fit-to-plane, and grid-artwork generation.
 *
 * ## Conventions (do not fork)
 *
 * - Document coordinates: `+X` right, `+Y` down (SVG initial user space).
 * - Axis `angle` is in **degrees** and denotes the direction of the line
 *   family *itself*: `direction = (cos θ, sin θ)`, `normal = (−sin θ, cos θ)`.
 *   With `+Y` down a positive angle therefore runs clockwise on screen.
 * - Affine/basis math is radians-free: a `Basis` is the linear part
 *   `[a, b, c, d]` in the same column convention as `Affine`
 *   (`x' = a·u + c·v`, `y' = b·u + d·v`).
 * - `spacing` is the **projected length of one lattice step along each axis**
 *   (the lattice constant `s`). It is deliberately *not* the perpendicular
 *   distance between lines of a family; those follow from the basis, and
 *   keeping one authored number prevents three families from drifting apart.
 *
 * A lattice generated by `b1 = s·(cos θ1, sin θ1)` and
 * `b2 = s·(cos θ2, sin θ2)` has perpendicular family spacings
 * `s·|sin Δ|` (family parallel to `b1` or `b2`) and `s·|sin Δ|` for the third
 * family when it is parallel to `b1 + b2` (the true-isometric vertical case).
 * Every family is emitted as `origin·n + k·p`, so all three families meet at
 * the same lattice points by construction.
 */

/** A linear 2×2 map in the shared column convention `[a, b, c, d]`. */
export type Basis = readonly [number, number, number, number];

/** Immutable 2-vector. */
export type Vec2 = readonly [number, number];

/** Basis whose columns are `u` and `v`. World-space by convention. */
export interface PlaneBasis {
  /** Direction of the `u` axis (column 0). */
  u: Vec2;
  /** Direction of the `v` axis (column 1). */
  v: Vec2;
}

/** Named construction planes for a Varve isometric grid. */
export type IsometricPlaneId = 'top' | 'front' | 'side';

export interface IsometricPlaneInfo {
  id: IsometricPlaneId;
  /** UI label. Stable, localised by the presentation layer if needed. */
  label: string;
  /** Axis labels this plane spans, in `u, v` order. */
  axes: readonly [string, string];
  /** Short copy used in tooltips and status text. */
  description: string;
}

