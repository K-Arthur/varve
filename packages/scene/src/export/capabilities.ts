/**
 * Export capability contracts (Strata export rebuild, M3).
 *
 * Every format declares what the encoder can actually do. The UI is
 * capability-driven: it must not show controls the encoder ignores, and must
 * not advertise formats the encoder cannot produce. `supported: false` means
 * no encoder exists in this app — the UI must not offer it.
 *
 * These tables mirror the real backends:
 *  - raster PNG/JPEG/WebP: browser canvas toBlob/convertToBlob (sRGB, 8-bit)
 *  - GIF: TS encoder (packages/engine/src/gifExport.ts)
 *  - SVG: @strata/codegen scene→SVG with subtree raster fallback
 *  - PDF family: strata-print (Rust) with a strict vector subset; browser has
 *    a minimal raster-PDF fallback
 *  - codegen: @strata/codegen emitters (semantic, not pixel-exact)
 *
 * Platform differences are expressed via `browser`/`desktop` flags; use
 * {@link capabilitiesForFormat} to get the contract for an active platform.
 */

import type { ExportFormat } from './model';

export type VectorSupportLevel = 'native' | 'approximated' | 'rasterized' | 'blocked';

export type FeatureSupportLevel = 'native' | 'approximated' | 'rasterized' | 'flatten' | 'blocked';

export interface FormatColorCapability {
  rgb: boolean;
  cmyk: boolean;
  grayscale: boolean;
  spotColors: boolean;
}

export interface FormatCapability {
  format: ExportFormat;
  label: string;
  /** False when no encoder exists — UI must not advertise this format. */
  supported: boolean;
  /** Why unsupported (shown when the user somehow has such a configuration). */
  reasonUnsupported?: string;
  /** Available in the web (browser/WASM) runtime. */
  browser: boolean;
  /** Available in the Tauri desktop runtime. */
  desktop: boolean;
  transparency: boolean;
  vector: VectorSupportLevel;
  text: 'native' | 'outline' | 'rasterized' | 'blocked';
  embeddedFonts: boolean;
  outlinedFonts: boolean;
  linkedImages: boolean;
  embeddedImages: boolean;
  iccEmbedding: boolean;
  colorSpaces: FormatColorCapability;
  alpha: boolean;
  animation: boolean;
  multiPage: boolean;
  bleed: boolean;
  cropMarks: boolean;
  printerMarks: boolean;
  metadata: boolean;
  compression: boolean;
  lossless: boolean;
  highBitDepth: boolean;
  masks: FeatureSupportLevel;
  blendModes: FeatureSupportLevel;
  filters: FeatureSupportLevel;
  adjustmentLayers: 'native' | 'rasterize' | 'blocked';
  /** Hard cap on the longest output dimension in px (0 = no cap). */
  maxDimensions: number;
  maxPageCount: number;
  /** True when the IR engine is always required to render this format. */
  needsEngine: boolean;
  /** True when output is rasterized end-to-end regardless of content. */
  rasterizedByDefault: boolean;
  /** True when this is a code generator rather than an image/vector encoder. */
  codegen: boolean;
}

