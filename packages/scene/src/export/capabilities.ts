export type PlatformKind = 'web' | 'tauri' | 'memory';

/**
 * The capability contract for a format on an active platform. Returns the
 * platform-clipped capability (a desktop-only format reports `browser: false`
 * when the active platform is web — callers should treat that as unavailable).
 */
export function capabilitiesForFormat(
  format: ExportFormat,
  platform: PlatformKind = 'web',
): FormatCapability {
  const base = FORMAT_CAPABILITIES[format];
  if (!base) {
    throw new Error(`No capability contract for format: ${String(format)}`);
  }
  if (platform === 'web') {
    return { ...base, browser: base.browser, desktop: base.desktop };
  }
  return base;
}

export function formatSupportedOnPlatform(
  format: ExportFormat,
  platform: PlatformKind = 'web',
): boolean {
  const cap = FORMAT_CAPABILITIES[format];
  if (!cap.supported) return false;
  return platform === 'tauri' ? cap.desktop : cap.browser;
}

/** Formats the UI may present for the active platform (supported and reachable). */
export function supportedFormats(platform: PlatformKind = 'web'): ExportFormat[] {
  return (Object.keys(FORMAT_CAPABILITIES) as ExportFormat[]).filter((format) =>
    formatSupportedOnPlatform(format, platform),
  );
}
