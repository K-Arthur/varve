let cached: MockupTemplateAsset[] | null = null;

/** The built-in catalog with content hashes materialized. */
export function getBuiltinMockupTemplates(): MockupTemplateAsset[] {
  if (cached) return cached;
  cached = rawTemplates.map((t) => ({ ...t, contentHash: hashMockupTemplate(t) }));
  return cached;
}

export function getBuiltinMockupTemplate(id: string): MockupTemplateAsset | undefined {
  return getBuiltinMockupTemplates().find((t) => t.id === id);
}
